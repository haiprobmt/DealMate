"""Request/response schemas của REST API v1 (hợp đồng với ứng dụng Android)."""
from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.schemas.domain import (
    Marketplace,
    MatchResult,
    PriceBreakdown,
    PriceConfidence,
    ProductAttributes,
    ProductQuery,
)


class ApiModel(BaseModel):
    model_config = ConfigDict(from_attributes=True)


# --- Search ---------------------------------------------------------------------------
class SearchRequest(ApiModel):
    query: str = Field(min_length=2, max_length=300)
    marketplaces: list[Marketplace] | None = None      # None == all
    quantity: int = Field(default=1, ge=1, le=20)
    include_similar: bool = True

    @field_validator("query")
    @classmethod
    def _strip(cls, v: str) -> str:
        v = " ".join(v.split())
        if len(v) < 2:
            raise ValueError("query too short")
        return v


class UrlSearchRequest(ApiModel):
    url: str = Field(min_length=10, max_length=2000)
    marketplaces: list[Marketplace] | None = None


class SourceResult(ApiModel):
    marketplace: Marketplace
    marketplace_name: str
    status: str            # ok | timeout | error | not_configured | not_implemented | skipped
    is_mock: bool
    offers_found: int = 0
    elapsed_ms: int = 0
    message: str | None = None


class SellerOut(ApiModel):
    name: str
    rating: float | None = None
    is_official_store: bool | None = None
    location: str | None = None


class OfferOut(ApiModel):
    id: int
    marketplace: Marketplace
    marketplace_name: str
    is_mock: bool
    title: str
    url: str
    image_url: str | None = None
    seller: SellerOut
    price: PriceBreakdown
    original_price: int | None = None
    match: MatchResult
    rating: float | None = None
    rating_count: int | None = None
    sold_count: int | None = None
    in_stock: bool | None = None
    retrieved_at: datetime
    is_stale: bool = False        # older than the freshness window
    over_budget: bool = False


class ProductGroup(ApiModel):
    product_id: int
    variant_id: int
    title: str
    image_url: str | None = None
    attributes: ProductAttributes
    match: MatchResult                   # how well this variant matches the user's request
    offers: list[OfferOut]               # sorted: verified asc, estimated asc, incomplete
    best_offer_id: int | None = None     # cheapest VERIFIED offer, else cheapest estimated
    lowest_final_price: int | None = None
    lowest_price_confidence: PriceConfidence | None = None
    offer_count: int = 0
    in_wishlist: bool = False


class BestOffer(ApiModel):
    variant_id: int
    variant_title: str
    offer_id: int
    final_price: int
    confidence: PriceConfidence
    marketplace: Marketplace
    marketplace_name: str
    explanation: str                     # Vietnamese, generated by deterministic code
    caveat: str | None = None            # e.g. a possibly-cheaper estimated/incomplete offer exists


class InterpretedQuery(ApiModel):
    raw: str
    interpreter: str                     # rules | ai
    spec: ProductQuery
    notes: list[str] = []


class Clarification(ApiModel):
    needed: bool = False
    message: str | None = None
    suggestions: list[str] = []


class SearchResponse(ApiModel):
    search_id: int
    search_type: str                     # text | image | url
    query: InterpretedQuery
    demo_mode: bool
    partial: bool                        # at least one marketplace did not answer
    sources: list[SourceResult]
    best: BestOffer | None = None
    groups: list[ProductGroup]           # exact + likely matches, best first
    similar_groups: list[ProductGroup]   # same family but a different variant/model
    excluded_count: int = 0              # listings judged "different" and dropped
    over_budget_count: int = 0
    clarification: Clarification = Clarification()
    generated_at: datetime


